-- finds a member by name or hash
local function member(tbl, name)
  if tbl == nil then return nil, nil end
  local ok, v = pcall(function() return tbl[name] end)
  if ok and v ~= nil then return name, v end
  local okh, h = pcall(H, name)
  if not okh or h == nil then return nil, nil end
  local ok2, v2 = pcall(function() return tbl[h] end)
  if ok2 and v2 ~= nil then return h, v2 end
  local want, found, fv = norm(h), nil, nil
  pcall(function()
    for k, val in pairs(tbl) do
      if norm(k) == want then found, fv = k, val end
    end
  end)
  if found ~= nil then return found, fv end
  return nil, nil
end

-- a member only when it is a function
local function fn_of(tbl, name)
  local _, v = member(tbl, name)
  if type(v) == "function" then return v end
  return nil
end

-- calls a member and eats the error
local function call(tbl, name, ...)
  local f = fn_of(tbl, name)
  if f == nil then return nil end
  local ok, v = pcall(f, ...)
  if ok then return v end
  return nil
end

local FC = {}
-- a member looked up once
local function fcache(tbl, name)
  if type(tbl) ~= "table" then return nil end
  local m = FC[tbl]
  if m == nil then m = {}; FC[tbl] = m end
  local f = m[name]
  if f ~= nil then return f end
  local _, v = member(tbl, name)
  if type(v) == "function" then
    m[name] = v
    return v
  end
  return nil
end

local DGET, PLAIN = nil, {}
-- reads a dvar string by hashed name
local function dv(name)
  if type(DGET) ~= "function" then DGET = fn_of(rawget(_G, "Dvar"), "GetDvarString") end
  if type(DGET) ~= "function" then return nil end
  local okh, key = pcall(HD, name)
  if not okh or key == nil then key = name end
  local ok, v = pcall(DGET, key)
  if ok and type(v) == "string" then return v end
  if key ~= name and PLAIN[name] ~= false then
    local ok2, v2 = pcall(DGET, name)
    if ok2 and type(v2) == "string" then
      PLAIN[name] = true
      return v2
    end
    PLAIN[name] = false
  end
  return nil
end

