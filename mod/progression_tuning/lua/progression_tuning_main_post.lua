-- one switch and its default
local function toggle(name, default_on)
  local v, how = dv(name), "string"
  if v == nil or v == "" then
    local n = dvi(name)
    if n ~= nil then v, how = tostring(n), "int" end
  end
  if v == nil or v == "" then return default_on, (default_on and "default-on" or "default-off") end
  if default_on then return v ~= "0", how .. "=" .. v end
  return v == "1", how .. "=" .. v
end

