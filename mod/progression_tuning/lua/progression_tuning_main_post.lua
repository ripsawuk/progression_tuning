-- strips a hashed key to its number
local function norm(v)
  local ok, s = pcall(tostring, v)
  if not ok or s == nil then return "?" end
  local h = string.match(s, "#x(%x+)")
  if not h then return "s:" .. s end
  return (string.gsub(string.sub(h, 2), "^0+", ""))
end

local REF_FAMILY = {}

-- the weapon family a ref names
local function family(ref)
  if type(ref) ~= "string" or ref == "" then return nil end
  local f = REF_FAMILY[ref]
  if f ~= nil then return f end
  local p = string.sub(ref, 1, 4)
  if p == "sat_" then f = "sat"
  elseif p == "t10_" then f = "t10"
  elseif p == "jup_" then f = "jup"
  elseif p == "iw9_" then f = "iw9" end
  if f ~= nil then REF_FAMILY[ref] = f end
  return f
end

