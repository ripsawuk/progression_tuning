-- the weapon own progression row id
local function resolve_gun(ref)
  local wp = csv_table("weaponProgressionAchievements")
  if wp == nil then return nil, "no CSV.weaponProgressionAchievements in this VM" end
  local id = tonumber(csv_lookup(wp, "weaponRef", ref, "weaponProgressionAchievementID"))
  if id == nil then
    local gs = csv_table("gunsmithChallenges")
    id = tonumber(csv_lookup(gs, "ref", ref, "id"))
  end
  if id ~= nil and id < 1 then id = nil end
  if id == nil then return nil, "no progression row answers for " .. clip(ref, 40) end
  return id, nil
end

