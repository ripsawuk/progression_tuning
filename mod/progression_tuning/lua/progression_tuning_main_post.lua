  end
  if type(rawget(_G, "Dvar")) ~= "table" then
    log("Dvar is not in this VM - not armed")
    return
  end
  refresh_toggles()
  S.front = front
  local HOW = S.toggles.how or {}
  if front then
    log("armed " .. VERSION .. " in the menu (log " .. (S.toggles.log and "on" or "off") .. ":"
      .. tostring(HOW.log) .. ") " .. vm_mark())
    arm_locks()
    pcall(diag_arm)
    if not ensure_timer(nil) then
      G.noClock = true
      log("no LUI root - the lock reader cannot poll, so it answers from the payload it already has")
    end
    return
  end
  log("armed " .. VERSION .. " in a match (level " .. (S.toggles.level and "on" or "off") .. ":"
    .. tostring(HOW.level) .. ", attach " .. (S.toggles.attach and "on" or "off") .. ":"
    .. tostring(HOW.attach) .. ", camo " .. (S.toggles.camo and "on" or "off") .. ":"
    .. tostring(HOW.camo) .. ", daily " .. (S.toggles.chal and "on" or "off") .. ":"
    .. tostring(HOW.chal) .. ", log " .. (S.toggles.log and "on" or "off") .. ":" .. tostring(HOW.log)
    .. ") reading ptsplash_paid " .. vm_mark())
  if not want(nil) then
    log("pt_on is off - armed but idle; set pt_on 1 in the console to turn it on")
  end
  arm_locks()
  pcall(diag_arm)
  if type(rawget(_G, "LUI")) ~= "table" then
    G.noClock = true
    log("LUI is not in this VM - not armed")
    return
  end
  if not ensure_timer(tick_match) then
    G.noClock = true
    log("no LUI root - the timer could not be armed, so nothing is drawn this match")
  end
end

local function maybe_arm()
  if S.armed then return end
  S.armed = true
  pcall(arm_core)
end

local function ready()
  maybe_arm()
  arm_locks()
  diag_arm()
end

A.ready = ready
maybe_arm()
