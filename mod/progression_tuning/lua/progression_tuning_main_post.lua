-- the csv file handle the table carries
local function csv_file(tbl)
  local file = tbl.file
  if file ~= nil and file ~= "" then return file end
  local getfile = fn_of(tbl, "GetFile")
  if getfile == nil then return file end
  local ok, v = pcall(getfile, tbl)
  if ok and v ~= nil then return v end
  return file
end

-- one cell of a csv row
local function csv_lookup(tbl, keycol, keyval, outcol)
  if type(tbl) ~= "table" or keyval == nil then return nil end
  local cols = tbl.cols
  if type(cols) ~= "table" then return nil end
  local kc, oc = cols[keycol], cols[outcol]
  if kc == nil or oc == nil then return nil end
  local lookup = fn_of(rawget(_G, "StringTable"), "tablelookup")
  if lookup == nil then return nil end
  local ok, v = pcall(lookup, csv_file(tbl), kc, keyval, oc)
  if ok and type(v) == "string" and v ~= "" then return v end
  return nil
end

-- the first csv attempt that answers
local function cell_pick(tries, outcol)
  local i = 1
  while i <= #tries do
    local t = tries[i]
    if t[1] ~= nil and t[3] ~= nil then
      local v = csv_lookup(t[1], t[2], t[3], outcol)
      if v ~= nil then return v, t[4] end
    end
    i = i + 1
  end
  return nil, nil
end

