-- splits a pipe list into numbers
local function numlist(s)
  local out, n = {}, 0
  if type(s) ~= "string" then return out, 0 end
  for tok in string.gmatch(s, "[^|]+") do
    local v = tonumber(tok)
    if v ~= nil then
      n = n + 1
      out[n] = v
    end
  end
  return out, n
end

-- a csv table by name
local function csv_table(name)
  local csv = rawget(_G, "CSV")
