-- thresholds whatever shape they came in
local function amounts_of(v)
  local th, k = {}, 0
  if type(v) == "table" then
    local i = 1
    while i <= #v do
      local n = tonumber(v[i])
      if n ~= nil then
        k = k + 1
        th[k] = n
      end
      i = i + 1
    end
  elseif type(v) == "string" then
    local l = numlist(v)
    local i = 1
    while l[i] ~= nil do
      th[i] = l[i]
      k = i
      i = i + 1
    end
  else
    local n = tonumber(v)
    if n ~= nil then
      k = 1
      th[1] = n
    end
  end
  if k > 1 then table.sort(th) end
  return th, k
end

