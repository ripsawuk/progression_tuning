-- rebuilds the lock bitmap when the serial moves
local function grefresh()
  local v = gstr(GN_VER)
  greadScope()
  greadset()
  greadUnlock()
  if v == nil or v == "" or v == "g11" then
    if not G.saidArm then
      G.saidArm = true
      if gstr(GN_ARM) == nil then
        log("g11 the payload dvars are not there yet - the client hook creates them at boot")
      end
    end
    if not G.saidNoPayload then
      G.saidNoPayload = true
      log("g11 no payload yet - running on the 96 published chunks")
    end
    return
  end
  if v == G.ver or v == G.badver then return end
  local serial, n, len = string.match(v, "^(%d+):(%d+):(%d+)$")
  if serial == nil or tonumber(n) ~= GPARTS or tonumber(len) ~= GHEXLEN then
    G.badver = v
    log("g11 header " .. tostring(v) .. " is not <serial>:33:65536 - refused, keeping the previous payload")
    return
  end
  if not G.noClock and S.tick < G.ready then return end
  G.ready = S.tick + GREBUILD_TICKS
  local parts, same = {}, true
  for i = 1, GPARTS do
    local p = gstr(GN_PART[i])
    if p == nil or string.len(p) == 0 then
      G.badver = v
      log("g11 part " .. (i - 1) .. " of " .. GPARTS .. " did not read - refused, keeping the previous payload")
      return
    end
    parts[i] = p
    if G.parts == nil or G.parts[i] ~= p then same = false end
  end
  if gstr(GN_VER) ~= v then return end
  if same then
    G.ver = v
    G.badver = nil
    G.skips = G.skips + 1
    return
  end
  local hex = table.concat(parts)
  if string.len(hex) ~= GHEXLEN then
    G.badver = v
    log("g11 payload is " .. string.len(hex) .. " chars, expected " .. GHEXLEN .. " - refused, keeping the previous payload")
    return
  end
  G.ver, G.hex, G.serial, G.parts = v, hex, tonumber(serial), parts
  G.epoch = G.epoch + 1
  G.doorSaid, G.doorN = {}, 0
  G.psaid, G.psaidN = {}, 0
  G.camoMapSaid, G.camoMissSaid = 0, 0
  G.askSeen, G.passSeen, G.passAt, G.passSaid = {}, {}, nil, 0
  if S.tracker ~= nil then S.tracker.drops, S.tracker.inN, S.tracker.outN = {}, 0, 0 end
  G.badver = nil
  log("g11 rebuilt from serial " .. G.serial
    .. (typepair() and " types=attachment,camo,reticle" or " types=scope-fallback"))
end

-- cuts the dll payload into guns
local function parse_paid(text)
  local res = { map = {}, n = 0, bad = 0, extra = 0, order = {}, state = "absent" }
  if type(text) ~= "string" or text == "" then return res end
  if text == "probe" then res.state = "probe"; return res end
  local head, rest = string.match(text, "^([^;]*);(.*)$")
  if head == nil then
    if text == "v1" then res.state = "v1" else res.state = "unknown" end
    return res
  end
  if head ~= "v1" then res.state = "unknown"; return res end
  res.state = "v1"
  for rec in string.gmatch(rest, "[^;]+") do
    local lid, total, mt = string.match(rec, "^(%d+):(%-?%d+):(%-?%d+)$")
    local l, t = tonumber(lid), tonumber(total)
    if l == nil or t == nil or t < 0 then
      res.bad = res.bad + 1
    elseif res.n >= PAID_MAX or res.map[l] ~= nil then
      res.extra = res.extra + 1
    else
      res.n = res.n + 1
      res.order[res.n] = l
      res.map[l] = { total = t, match = tonumber(mt) or 0 }
    end
  end
  return res
end

-- the one line about the payload state
local function paid_say(state, n, bad)
  if S.paidlogged >= PAID_LOG_CAP then return end
  S.paidlogged = S.paidlogged + 1
  local refused = ""
  if bad ~= nil and bad > 0 then refused = " (" .. tostring(bad) .. " record(s) refused)" end
  if state == "dll" then
    log("paid source dll - ptsplash_paid carries " .. tostring(n) .. " gun(s)" .. refused
      .. ": each gun's own profile total, which is what every level here is read from")
  elseif state == "probe" then
    log("paid source probe - the DLL is attached and has paid nothing this process, so no display change")
  elseif state == "absent" then
    log("paid source absent - ptsplash_paid is not published, so no display change and nothing is drawn")
  elseif state == "empty" then
    log("paid source empty - ptsplash_paid carries no gun this match" .. refused .. ", so no display change")
  else
    log("paid source ignored - ptsplash_paid carries no record this build can read" .. refused
      .. ", so no display change")
  end
end

-- reads the payload when it changed
local function paid_read()
  if S.paidraw ~= nil and S.tick % PAID_EVERY ~= 0 then return end
  local text = dv("ptsplash_paid")
  if text == S.paidraw then return end
  S.paidraw = text
  local res = parse_paid(text)
  local state, n, bad = res.state, res.n, res.bad + res.extra
  S.paid, S.paidN, S.paidorder = res.map, n, res.order
  S.paidon = (state == "v1" and n >= 1)
  local shown = state
  if state == "v1" and n < 1 then shown = "empty" end
  if shown == "v1" then shown = "dll" end
  if S.paidsaid ~= shown then paid_say(shown, n, bad) end
  S.paidsaid = shown
end

