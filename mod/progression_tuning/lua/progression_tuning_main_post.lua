-- the one timer and its stale guard
local function ensure_timer(work)
  if timerEl ~= nil then
    local ok, parent = pcall(function() return timerEl:getParent() end)
    if ok and parent then return true end
  end
  local getroot = fn_of(rawget(_G, "LUI"), "GetRoot")
  if getroot == nil then return false end
  local okR, rootEl = pcall(getroot)
  if not okR or rootEl == nil then return false end
  local newEl = fn_of(rawget(_G, "LUI"), "UIElement")
  local el
  if newEl ~= nil then
    local okE, v = pcall(newEl)
    if okE then el = v end
  end
  if el == nil then
    local _, uie = member(rawget(_G, "LUI"), "UIElement")
    if type(uie) == "table" then
      local f = fn_of(uie, "new")
      if f ~= nil then
        local okN, v = pcall(f)
        if okN then el = v end
      end
    end
  end
  if el == nil then return false end
  if not pcall(function() return rootEl:addElement(el) end) then return false end
  timerEl = el
  S.gen = (S.gen or 0) + 1
  local myGen = S.gen
  -- one timer step
  local function tick()
    if not S.enabled or myGen ~= S.gen then return end
    S.tick = S.tick + 1
    if S.tick == 1 then pcall(report_parts) end
    if S.tick % TOGGLE_TICKS == 0 then pcall(refresh_toggles) end
    if S.tick % TOGGLE_TICKS == 0 then pcall(diag_poll) end
    if work ~= nil then pcall(work) end
    pcall(gtick)
    local okw = pcall(function() el:Wait(TICK_MS).onComplete = tick end)
    if not okw and said("timerlost") then
      log("timer lost - the hud rebuilt under this element")
    end
  end
  pcall(function() el:Wait(TICK_MS).onComplete = tick end)
  return true
end

