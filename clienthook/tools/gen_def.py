"""Generate the .def that forwards every export of a system DLL to a renamed copy of itself.

Forwarding (rather than stubs) means no signature has to be reproduced: the loader resolves each
export from the target module, so the proxy answers exactly what the real DLL answers.

    python clienthook\\tools\\gen_def.py version   ->  clienthook\\src\\version_proxy.def
"""
import os
import sys

import pefile

SYSTEM32 = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32")
SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src")


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    dll = sys.argv[1].lower()
    if not dll.endswith(".dll"):
        dll += ".dll"
    target = os.path.join(SYSTEM32, dll)
    orig = os.path.splitext(dll)[0] + "_orig"

    pe = pefile.PE(target)
    exports = [s for s in pe.DIRECTORY_ENTRY_EXPORT.symbols if s.name]
    nameless = [s for s in pe.DIRECTORY_ENTRY_EXPORT.symbols if not s.name]

    lines = [
        "; generated by clienthook\\tools\\gen_def.py - do not edit by hand",
        f"; forwards every named export of {dll} to {orig}",
        f"LIBRARY {os.path.splitext(dll)[0]}",
        "EXPORTS",
    ]
    for s in sorted(exports, key=lambda x: x.name):
        name = s.name.decode()
        lines.append(f"    {name}={orig}.{name}")

    out = os.path.normpath(os.path.join(SRC, os.path.splitext(dll)[0] + "_proxy.def"))
    with open(out, "w", encoding="ascii", newline="\r\n") as fh:
        fh.write("\n".join(lines) + "\n")

    print(f"{len(exports)} named exports -> {out}")
    if nameless:
        print(f"WARNING: {len(nameless)} ordinal-only exports cannot be forwarded by name: "
              f"{[s.ordinal for s in nameless]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
